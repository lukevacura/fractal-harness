import subprocess
from pathlib import Path

import pytest

from fractal_harness import probes
from fractal_harness.cache import ClaimCache
from fractal_harness.cli import main
from fractal_harness.probes import ProbeError


def _repo(tmp_path: Path):
    subprocess.run(["git", "init", "-q"], cwd=tmp_path, check=True)
    (tmp_path / "src").mkdir(exist_ok=True)
    (tmp_path / "src" / "nearest.rs").write_text("pub struct Nearest;\nfn rank_key(x: u32) -> u32 { x }\n")
    (tmp_path / "src" / "other.rs").write_text("fn helper() {}\n")


PAT = {"type": "only_in", "pattern": r"fn rank_key", "paths": ["src/**/*.rs"], "files": ["src/nearest.rs"],
       "concept": "ranking expression"}
KIND = {"type": "only_in", "kind": "struct", "name": r"Nearest\w*", "paths": ["src/**/*.rs"],
        "files": ["src/nearest.rs"]}


def test_only_in_passes_while_one_owner_and_fails_on_a_second_copy(tmp_path):
    _repo(tmp_path)
    assert probes.run(PAT, tmp_path).passed and probes.run(KIND, tmp_path).passed
    (tmp_path / "src" / "other.rs").write_text("fn rank_key(x: u32) -> u32 { x + 1 }\npub struct NearestK;\n")
    r = probes.run(PAT, tmp_path)
    assert not r.passed and "src/other.rs:1" in r.detail and r.matches == [("src/other.rs", 0)]
    assert not probes.run(KIND, tmp_path).passed          # NearestK is the second "nearest" abstraction


def test_only_in_fails_when_the_owner_loses_it_and_works_on_an_overlay(tmp_path):
    _repo(tmp_path)
    (tmp_path / "src" / "nearest.rs").write_text("// moved\n")
    assert "moved or renamed" in probes.run(PAT, tmp_path).detail
    assert probes.run({**PAT, "min": 0}, tmp_path).passed
    _repo(tmp_path)
    assert not probes.run(PAT, tmp_path, overlay={"src/new.rs": "fn rank_key() {}\n"}).passed   # pre-edit hook


def test_only_in_validation():
    for bad in ({"type": "only_in", "paths": ["a"], "files": ["b"]},
                {**PAT, "kind": "fn"},
                {**KIND, "kind": "widget"},
                {**PAT, "files": []}):
        with pytest.raises(ProbeError):
            probes.validate(bad)


def test_cli_only_in_and_concepts_registry(tmp_path, capsys):
    _repo(tmp_path)
    base = ["--root", str(tmp_path)]
    assert main(base + ["only-in", "ranking expression", "--pattern", "fn rank_key", "--in", "src/nearest.rs",
                        "--paths", "src/**/*.rs"]) == 0
    capsys.readouterr()
    out_file = tmp_path / "CONCEPTS.md"
    assert main(base + ["concepts", "--write", str(out_file)]) == 0
    out = capsys.readouterr().out
    assert "ranking expression" in out and "src/nearest.rs" in out and "verified" in out
    assert "Generated by" in out_file.read_text()
    (tmp_path / "src" / "other.rs").write_text("fn rank_key() {}\n")
    c = ClaimCache(tmp_path)
    c.refresh()
    c.update()
    c.close()
    main(base + ["concepts"])
    assert "failed" in capsys.readouterr().out


def test_kind_name_with_anchors_matches_the_whole_identifier_and_a_failing_rule_is_refused(tmp_path, capsys):
    _repo(tmp_path)
    (tmp_path / "src" / "other.rs").write_text("pub fn r_bias() {}\nfn r_bias_2() {}\n")
    probe = {"type": "only_in", "kind": "fn", "name": "^r_bias$", "paths": ["src/**/*.rs"], "files": ["src/other.rs"]}
    assert probes.run(probe, tmp_path).passed                      # r_bias_2 is a different identifier
    base = ["--root", str(tmp_path)]
    assert main(base + ["only-in", "bias", "--kind", "fn", "--name", "^r_bias$", "--in", "src/other.rs",
                        "--paths", "src/**/*.rs"]) == 0
    capsys.readouterr()
    # a rule that already fails is an error at creation, not a failing claim
    assert main(base + ["only-in", "bias", "--kind", "fn", "--name", "r_bias", "--in", "src/nearest.rs",
                        "--paths", "src/**/*.rs"]) == 1
    assert "created failing" in capsys.readouterr().err


def test_only_in_decision_flag_is_stored_and_listed_in_the_registry(tmp_path, capsys):
    from fractal_harness.concepts import decision_ids
    _repo(tmp_path)
    base = ["--root", str(tmp_path)]
    assert main(base + ["only-in", "nearest order", "--pattern", "fn rank_key", "--in", "src/nearest.rs",
                        "--paths", "src/**/*.rs", "--decision", "S5", "--decision", "S6"]) == 0
    capsys.readouterr()
    c = ClaimCache(tmp_path)
    assert decision_ids(c) == {"S5": ["nearest order"], "S6": ["nearest order"]}
    c.close()
    main(base + ["concepts"])
    assert "S5, S6" in capsys.readouterr().out


