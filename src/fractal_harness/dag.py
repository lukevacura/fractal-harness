"""The DAG view, generated: one line per node from the specs and the ledger, nothing hand-edited.

Each line: id, derived state (status.py), a one-line summary, the `uses` edges (`parents:`, a contract relied
on) and the `after` edges (sequencing only; shown apart, never merged), and a link to the spec. Prose belongs
in the spec; the summary is only its first sentence. Output is a pure function of specs + ledger, in a stable
order (layer, then id), so it diffs cleanly.

SOUND: ids, states, edges, layers (declared headers + verdicts). COSMETIC: the summary text (first sentence of
`guarantee:`, else of the first prose paragraph); it gates nothing.
"""

from __future__ import annotations

import json
import os
import re
from pathlib import Path

from . import graph_query, status
from .cache import ClaimCache
from .nodes import body, parse_header
from .symbols import SymbolError, at

SUMMARY_MAX = 140


def first_sentence(text: str) -> str:
    text = re.sub(r"\s+", " ", text).strip()
    m = re.match(r"(.+?[.!?])(?:\s|$)", text)
    s = (m.group(1) if m else text)
    return s if len(s) <= SUMMARY_MAX else s[:SUMMARY_MAX - 1].rstrip() + "…"


def summary(root: Path, spec: str) -> str:
    f = at(root, spec)
    if not f.is_file():
        return "(spec missing)"
    text = f.read_text(errors="replace")
    try:
        h = parse_header(text)
    except SymbolError:
        h = None
    if h and h.guarantee:
        return first_sentence(h.guarantee)
    for para in re.split(r"\n\s*\n", body(text) if h else text):
        lines = [x for x in para.strip().splitlines() if x.strip() and not x.lstrip().startswith(("#", "---", "|", ">"))]
        if lines:
            return first_sentence(" ".join(lines))
    return ""


def build(cache: ClaimCache, root: Path, out_dir: Path | None = None) -> dict:
    g = graph_query.dag(cache, root)
    derived = status.derive_all(cache, root)
    base = (out_dir or root).resolve()
    rows = []
    for n in g["nodes"]:
        spec = cache.store.get_node(n)["spec"]
        rows.append({"id": n, "state": derived[n]["state"], "reason": derived[n]["reasons"][0],
                     "summary": summary(root, spec), "uses": g["uses"][n], "after": g["after"][n],
                     "spec": spec, "path": os.path.relpath(at(root, spec), base),
                     "layer": g["layer"].get(n)})
    rows.sort(key=lambda r: (r["layer"] is None, r["layer"] or 0, r["id"]))
    return {"nodes": rows, "cycles": g["cycles"]}


def render_md(d: dict) -> str:
    out = ["<!-- generated by `fractal dag`; edit the specs, not this file -->", "# Node DAG", "",
           "`uses` = contract relied on (DAG); `after` = sequencing only."]
    layer = object()
    if not d["nodes"]:
        out += ["", "(no registered nodes)"]
    for r in d["nodes"]:
        if r["layer"] != layer:
            layer = r["layer"]
            out += ["", f"## Layer {layer}" if layer is not None else "## Cyclic or unresolved", ""]
        edges = [f"uses: {', '.join(r['uses'])}"] if r["uses"] else []
        edges += [f"after: {', '.join(r['after'])}"] if r["after"] else []
        out.append(" · ".join([f"**{r['id']}** `{r['state']}`", r["summary"] or "(no summary)", *edges,
                                f"[spec]({r['path']})"]))
    if d["cycles"]:
        out += ["", f"Cycles through: {', '.join(d['cycles'])}"]
    return "\n".join(out) + "\n"


def render(d: dict, fmt: str = "md") -> str:
    if fmt == "json":
        return json.dumps(d, indent=2, sort_keys=True, ensure_ascii=False) + "\n"
    return render_md(d)
